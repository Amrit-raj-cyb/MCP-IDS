"""Log record format and JSON-RPC message classification.

Every line the proxy sees becomes one :class:`LogEvent`. This schema *is* the
raw dataset format, so it is versioned (``schema_version``) and documented in
docs/dataset.md. Change it only by bumping the version.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from datetime import UTC, datetime
from typing import Any

SCHEMA_VERSION = 2  # v2 adds mono_ns (precise, cross-process ordering clock)

CLIENT_TO_SERVER = "client_to_server"
SERVER_TO_CLIENT = "server_to_client"
PROXY = "proxy"  # lifecycle events generated by the proxy itself


@dataclass
class LogEvent:
    schema_version: int
    session_id: str
    server_id: str
    seq: int                    # per-proxy counter (order within this server's file)
    ts_ns: int                  # wall clock, ns; used to merge files of one session
    timestamp: str              # same instant, ISO-8601 UTC (human readable)
    direction: str              # client_to_server | server_to_client | proxy
    kind: str                   # request | response | notification | error | batch | invalid | lifecycle
    method: str | None          # for responses: the method of the matching request
    jsonrpc_id: Any             # JSON-RPC id (int or str) or None
    message_size: int           # bytes of the line as sent, excluding the line terminator
    is_error: bool              # JSON-RPC error, or a tool result with isError=true
    error_code: int | None
    error_message: str | None
    request_seq: int | None     # responses: seq of the matching request
    latency_ms: float | None    # responses: time since the matching request
    body: Any                   # parsed JSON message (None if unparseable)
    raw: str | None             # only for invalid lines: the text that failed to parse
    # v2: time.perf_counter_ns() when the proxy read the line. Precise (100 ns
    # on Windows, where ts_ns only ticks every ~15.6 ms) and shared by all
    # processes on the host, so it orders events across proxies. Not wall time.
    mono_ns: int | None = None

    def to_json(self) -> str:
        return json.dumps(asdict(self), ensure_ascii=False, separators=(",", ":"))


def iso(ts_ns: int) -> str:
    return datetime.fromtimestamp(ts_ns / 1e9, UTC).isoformat(timespec="microseconds")


def classify(msg: Any) -> tuple[str, str | None, Any]:
    """Return ``(kind, method, id)`` for a parsed JSON-RPC message.

    JSON-RPC 2.0 rules: a *request* has ``method`` and ``id``; a
    *notification* has ``method`` but no ``id``; a *response* has ``id`` and
    ``result``; an *error* response has ``id`` and ``error``.
    """
    if isinstance(msg, list):
        return "batch", None, None
    if not isinstance(msg, dict):
        return "invalid", None, None
    msg_id = msg.get("id")
    if "method" in msg:
        return ("request" if "id" in msg else "notification"), msg["method"], msg_id
    if "error" in msg:
        return "error", None, msg_id
    if "result" in msg:
        return "response", None, msg_id
    return "invalid", None, msg_id


def error_info(msg: Any) -> tuple[bool, int | None, str | None]:
    """Detect protocol errors *and* tool-level errors (``result.isError``)."""
    if not isinstance(msg, dict):
        return False, None, None
    err = msg.get("error")
    if isinstance(err, dict):
        return True, err.get("code"), err.get("message")
    result = msg.get("result")
    if isinstance(result, dict) and result.get("isError") is True:
        return True, None, None
    return False, None, None
